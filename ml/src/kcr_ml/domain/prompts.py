def build_brief_user_prompt(facts: str) -> str:
    """User message for the brief: deterministic facts block produced by code."""
    return f"Факты о клиенте (из базы данных сервиса):\n\n{facts}\n\nНапиши сводку перед звонком."


def build_prioritize_explain_prompt(criteria_description: str, top_list: str) -> str:
    """User message for the prioritization explanation call."""
    return f"Критерии выборки: {criteria_description}\n\nСписок клиентов (лучшие позиции сверху):\n{top_list}"
