-- Предметная сущность "Срез состояния передачи документов": сколько документов клиент
-- должен был передать за отчётный период и сколько ещё не передано, по состоянию на
-- дату среза. Каждая загрузка создаёт новый срез, предыдущие не перезаписываются
-- (отслеживание динамики); дубликаты (клиент, период, дата) допустимы по построению.
-- total_documents nullable: повторный срез может загружаться без этого поля -- тогда
-- при импорте значение копируется из последнего среза того же клиента и периода
-- (сервисный слой импорта); % непереданных -- производное, не хранится, вычисляется при выдаче.

CREATE TABLE document_transfer_snapshots (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id                 BIGINT NOT NULL,
    reporting_period          VARCHAR(255) NOT NULL,
    snapshot_date             DATE NOT NULL,
    total_documents           INT,
    not_transferred_documents INT NOT NULL,
    CONSTRAINT fk_document_transfer_snapshots_clients
        FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT document_transfer_snapshots_total_check
        CHECK (total_documents IS NULL OR total_documents >= 0),
    CONSTRAINT document_transfer_snapshots_not_transferred_check
        CHECK (not_transferred_documents >= 0
               AND (total_documents IS NULL OR not_transferred_documents <= total_documents))
);

CREATE INDEX idx_document_transfer_snapshots_client_period_date
    ON document_transfer_snapshots (client_id, reporting_period, snapshot_date);
