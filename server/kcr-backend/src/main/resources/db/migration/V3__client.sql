-- Предметная сущность "Клиент" (карточка клиента, идентифицируемого кодом KCR).
-- Обязательные поля: код KCR (уникальный), ИНН, название организации;
-- остальные заполняются по мере наличия в выгрузке (null = данных нет).
-- Булевы поля nullable: null = нет данных в выгрузке, false = известное значение.

CREATE TABLE clients (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kcr_code          VARCHAR(255) NOT NULL,
    inn               VARCHAR(12)  NOT NULL,
    kpp               VARCHAR(9),
    organization_name VARCHAR(255) NOT NULL,
    internal_id       VARCHAR(255),
    client_type       VARCHAR(255),
    kcr_active        BOOLEAN,
    kcr_blocked       BOOLEAN,
    tariff            VARCHAR(255),
    ekb_travel_time   VARCHAR(255),
    manager           VARCHAR(255),
    flags             VARCHAR(255)[],
    contact_person    VARCHAR(255),
    contact_phone     VARCHAR(255),
    contact_email     VARCHAR(255),
    CONSTRAINT uk_clients_kcr_code UNIQUE (kcr_code),
    CONSTRAINT clients_client_type_check
        CHECK (client_type IN ('VIP', 'TECH_PARTNER', 'WORKS_VIA_MP', 'NEWCOMER'))
);
