-- и единый закреплённый список на обзвон для операторов (пул обзвона, §11.4).

ALTER TABLE document_transfer_snapshots
    ADD COLUMN dynamics_category VARCHAR(32),
    ADD COLUMN previous_not_transferred INT,
    ADD CONSTRAINT document_transfer_snapshots_dynamics_check
        CHECK (dynamics_category IS NULL OR dynamics_category IN (
            'NO_DEBT', 'FIRST_OCCURRENCE', 'DECREASING',
            'UNCHANGED_OR_GROWING', 'REAPPEARED', 'PERSISTENT', 'NEWCOMER_RISK'
        ));

CREATE TABLE call_list_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     BIGINT NOT NULL,
    created_by_id BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    position      INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_call_list_items_client FOREIGN KEY (client_id) REFERENCES clients (id) ON DELETE CASCADE,
    CONSTRAINT fk_call_list_items_user FOREIGN KEY (created_by_id) REFERENCES users (id),
    CONSTRAINT uk_call_list_items_client UNIQUE (client_id)
);

CREATE INDEX idx_call_list_items_position ON call_list_items (position);
CREATE INDEX idx_call_list_items_created_at ON call_list_items (created_at);
