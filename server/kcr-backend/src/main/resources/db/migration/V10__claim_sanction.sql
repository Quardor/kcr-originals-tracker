-- Претензионная работа (§11.3): претензия добавляется администратором, санкции --
-- меры по претензии и статус их применения. Мутации претензий и санкций дублируются
-- событиями CLAIM/SANCTION в общей истории клиента (client_events, V9).
-- Справочники статусов (вопрос 3 §11.7, наборы приняты 2026-11-08):
--   претензия: NEW -> SENT -> RECEIVED -> SATISFIED | CANCELLED;
--   санкция:   PLANNED -> APPLIED | CANCELLED. Название санкции — свободный текст,
--   справочник доступных санкций не определён заказчиком (§11.7).

CREATE TABLE claims (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id              BIGINT NOT NULL,
    number                 VARCHAR(64) NOT NULL,
    claim_date             DATE NOT NULL,
    incident_number        VARCHAR(64),
    received_by_client_at  DATE,
    status                 VARCHAR(32) NOT NULL DEFAULT 'NEW',
    comment                TEXT,
    created_at             TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_claims_clients
        FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT claims_status_check
        CHECK (status IN ('NEW', 'SENT', 'RECEIVED', 'SATISFIED', 'CANCELLED'))
);

CREATE INDEX idx_claims_client_id
    ON claims (client_id);

CREATE TABLE sanctions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    BIGINT NOT NULL,
    name        VARCHAR(128) NOT NULL,
    status      VARCHAR(32) NOT NULL DEFAULT 'PLANNED',
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_sanctions_claims
        FOREIGN KEY (claim_id) REFERENCES claims (id),
    CONSTRAINT sanctions_status_check
        CHECK (status IN ('PLANNED', 'APPLIED', 'CANCELLED'))
);

CREATE INDEX idx_sanctions_claim_id
    ON sanctions (claim_id);
