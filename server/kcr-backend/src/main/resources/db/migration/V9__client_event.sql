-- Единая история клиента (сценарии 6, 9, 10, 12 ТЗ): любая мутация (звонок, письмо,
-- комментарий, смена этапа, переназначение, загрузка данных, претензия, санкция)
-- оставляет запись с датой, временем и автором. Одна широкая таблица с типом и
-- nullable-полями; JOIN-наследование подтипов — при необходимости позже (§11.3).
-- Поля call_result/agreement/client_deadline/next_contact_at/record_url имеют смысл
-- только для CALL; системные типы (STAGE_CHANGED, ASSIGNEE_CHANGED, IMPORT, CLAIM,
-- SANCTION) создаются сервисным слоем, вручную через API заводятся только
-- CALL/LETTER_SENT/COMMENT.

CREATE TABLE client_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT NOT NULL,
    author_id       BIGINT NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,
    type            VARCHAR(32) NOT NULL,
    comment         TEXT,
    call_result     VARCHAR(32),
    agreement       TEXT,
    client_deadline DATE,
    next_contact_at DATE,
    record_url      TEXT,
    CONSTRAINT fk_client_events_clients
        FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_client_events_users
        FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT client_events_type_check
        CHECK (type IN ('CALL', 'LETTER_SENT', 'COMMENT', 'STAGE_CHANGED',
                        'ASSIGNEE_CHANGED', 'IMPORT', 'CLAIM', 'SANCTION')),
    CONSTRAINT client_events_call_result_check
        CHECK (call_result IN ('CONNECTED', 'NO_ANSWER', 'CALLBACK_LATER', 'WRONG_NUMBER'))
);

-- история выдаётся от новых к старым
CREATE INDEX idx_client_events_client_created
    ON client_events (client_id, created_at DESC, id DESC);
