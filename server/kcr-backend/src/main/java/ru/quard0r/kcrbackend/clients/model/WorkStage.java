package ru.quard0r.kcrbackend.clients.model;

/**
 * Этап работы с клиентом — хранится отдельно от состояния передачи документов
 * (прямое требование ТЗ, §11.2). Порядок значений отражает типичную цепочку
 * (выявлены непереданные → первый звонок → ожидание срока → повторная проверка →
 * второй звонок → претензионная работа → завершение), но реальные
 * последовательности могут отличаться по клиентам и циклы повторяются в следующих
 * периодах, поэтому допустимые переходы не контролируются. IN_POOL — администратор
 * отобрал клиента в общий пул, оператор ещё не взял (набор предварительный,
 * вопрос 1 §11.7: правила смены приняты 2026-11-08 — админ любой этап, оператор
 * только рабочие этапы своих клиентов).
 */
public enum WorkStage {
    NOT_IN_WORK,
    IN_POOL,
    FIRST_CALL,
    WAITING_CLIENT_DEADLINE,
    RECHECK,
    SECOND_CALL,
    CLAIM_WORK,
    COMPLETED;

    /**
     * Рабочий этап — доступен оператору; NOT_IN_WORK и IN_POOL управляют
     * жизненным циклом списка работы и остаются за администратором.
     */
    public boolean isWorkStage() {
        return this != NOT_IN_WORK && this != IN_POOL;
    }
}
