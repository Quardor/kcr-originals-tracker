package ru.quard0r.kcrbackend.snapshots.model;

/**
 * Категория динамики состояния передачи документов клиента (§11.2 ARCHITECTURE.md).
 * Хранится именем значения в varchar + CHECK (V11).
 */
public enum DynamicsCategory
{
    /** Все переданы: not_transferred_documents = 0, работы не требует. */
    NO_DEBT,

    /** Впервые появились: за прошлые периоды всё передано, за последний — долг. */
    FIRST_OCCURRENCE,

    /** Уменьшается: долг меньше, чем в предыдущем срезе. */
    DECREASING,

    /** Не меняется / растёт: долг не уменьшился относительно предыдущего среза. */
    UNCHANGED_OR_GROWING,

    /** Повторное появление: цикл был завершён (долг был 0), долг появился снова. */
    REAPPEARED,

    /** Сохраняется длительно: непереданные в нескольких периодах подряд. */
    PERSISTENT,

    /** Долг у новичка: подключение < 6 месяцев назад и есть долг. */
    NEWCOMER_RISK
}
